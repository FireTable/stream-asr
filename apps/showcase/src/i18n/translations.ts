export type Lang = 'zh-cn' | 'en' | 'zh-hk';

export function getInitialLang(): Lang {
  if (typeof window === 'undefined') return 'zh-cn';
  try {
    const saved = localStorage.getItem('stream_asr_lang');
    if (saved === 'zh-cn' || saved === 'en' || saved === 'zh-hk') return saved as Lang;
    if (saved === 'zh') return 'zh-cn';
    if (saved === 'yue' || saved === 'zh-tw' || saved === 'zh-hk') return 'zh-hk';

    // Fallback to browser preference
    const nav = (navigator.language || (navigator as any).userLanguage || '').toLowerCase();
    if (nav.startsWith('zh-hk') || nav.startsWith('zh-mo') || nav.startsWith('zh-tw') || nav.startsWith('yue')) return 'zh-hk';
    if (nav.startsWith('zh')) return 'zh-cn';
    return 'en';
  } catch (e) {
    return 'zh-cn';
  }
}

